#!/usr/bin/env python3
"""Regenerates the committed schema assets from the Open WebUI web app's reference database.

  app/src/main/assets/webui_schema.sql                   DDL (no data) used to create the app database
  app/src/test/resources/open-webui-schema-fingerprint.txt tables/columns/indexes compared by SchemaTest

Usage: export_open_webui_schema.py <webui.db> <repo-root>
Only DDL and the alembic revision are read; no user data is copied.
"""
import os
import sqlite3
import sys

src, root = sys.argv[1], sys.argv[2]
con = sqlite3.connect(f"file:{src}?mode=ro", uri=True)
rows = con.execute(
    "select type, name, tbl_name, sql from sqlite_master "
    "where sql is not null and name not like 'sqlite_%' order by rowid").fetchall()
rev = con.execute("select version_num from alembic_version").fetchone()[0]

out = ["-- Generated by scripts/export_open_webui_schema.py from the Open WebUI web app's webui.db reference. Do not edit.",
       f"-- alembic revision: {rev}"]
for _, _, _, sql in rows:
    out.append("-- ;;")
    out.append(sql.strip())
out.append("-- ;;")
out.append(f"INSERT INTO alembic_version (version_num) VALUES ('{rev}')")
asset = os.path.join(root, "app/src/main/assets/webui_schema.sql")
os.makedirs(os.path.dirname(asset), exist_ok=True)
open(asset, "w").write("\n".join(out) + "\n")

fp = [f"alembic {rev}"]
tables = sorted(n for t, n, _, _ in rows if t == "table")
for t in tables:
    fp.append(f"table {t}")
    for cid, name, typ, notnull, dflt, pk in con.execute(f'pragma table_info("{t}")'):
        fp.append(f"  col {cid} {name} {typ} notnull={notnull} default={dflt} pk={pk}")
    idx = []
    for _, iname, unique, origin, partial in con.execute(f'pragma index_list("{t}")'):
        cols = ",".join(str(c[2]) for c in con.execute(f'pragma index_info("{iname}")'))
        label = "auto" if iname.startswith("sqlite_autoindex") else iname
        idx.append(f"  index {label} unique={unique} origin={origin} partial={partial} cols={cols}")
    fp.extend(sorted(idx))
res = os.path.join(root, "app/src/test/resources/open-webui-schema-fingerprint.txt")
os.makedirs(os.path.dirname(res), exist_ok=True)
open(res, "w").write("\n".join(fp) + "\n")
print(f"{len(tables)} tables, {sum(1 for r in rows if r[0]=='index')} explicit indexes, alembic {rev}")
